def build_cards() -> list[dict]:
    cards = []
    for row in MAJOR:
        cid, zh, en, num, suit, rank, elem, uk, rk, um, rm = row
        cards.append({
            "id": cid, "name_zh": zh, "name_en": en,
            "arcana": "major", "suit": suit, "number": num, "rank": rank,
            "element": elem,
            "image_path": f"/static/cards/{cid}.jpg",
            "upright_keywords": uk, "reversed_keywords": rk,
            "upright_meaning": um, "reversed_meaning": rm,
        })

    suit_meanings = {
        "wands": WANDS_NUM, "cups": CUPS_NUM,
        "swords": SWORDS_NUM, "pentacles": PENTACLES_NUM,
    }

    for suit_id, (suit_zh, suit_en, elem) in MINOR_SUITS.items():
        meanings = suit_meanings[suit_id]
        for num in range(1, 11):
            zh_num, en_num = NUMBER_NAMES[num]
            uk, rk, um, rm = meanings[num - 1]
            name_zh = f"{suit_zh}{zh_num}"
            name_en = f"{en_num} of {suit_en}"
            cid = f"{suit_id}-{en_num.lower()}"
            cards.append({
                "id": cid, "name_zh": name_zh, "name_en": name_en,
                "arcana": "minor", "suit": suit_id, "number": num, "rank": None,
                "element": elem,
                "image_path": f"/static/cards/{cid}.jpg",
                "upright_keywords": uk, "reversed_keywords": rk,
                "upright_meaning": um, "reversed_meaning": rm,
            })

        for rank_id, (rank_zh, rank_en) in COURT_NAMES.items():
            uk, rk, um, rm = COURT_MEANINGS[suit_id][rank_id]
            name_zh = f"{suit_zh}{rank_zh}"
            name_en = f"{rank_en} of {suit_en}"
            cid = f"{suit_id}-{rank_id}"
            rank_num = {"page": 11, "knight": 12, "queen": 13, "king": 14}[rank_id]
            cards.append({
                "id": cid, "name_zh": name_zh, "name_en": name_en,
                "arcana": "minor", "suit": suit_id, "number": rank_num, "rank": rank_id,
                "element": elem,
                "image_path": f"/static/cards/{cid}.jpg",
                "upright_keywords": uk, "reversed_keywords": rk,
                "upright_meaning": um, "reversed_meaning": rm,
            })

    return cards


if __name__ == "__main__":
    out = Path(__file__).parent.parent / "app" / "data" / "cards.json"
    cards = build_cards()
    assert len(cards) == 78, f"Expected 78 cards, got {len(cards)}"
    with open(out, "w", encoding="utf-8") as f:
        json.dump(cards, f, ensure_ascii=False, indent=2)
    print(f"Generated {len(cards)} cards -> {out}")
